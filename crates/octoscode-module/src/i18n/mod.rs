//! A24 — the UI language and its Chinese catalog: the web's
//! `features/preferences/ui-text.tsx` (`createUiText`, the lazily loaded
//! `loadChineseCatalog`) and the display preference's `language`
//! (`features/preferences/model.ts`), natively.
//!
//! - **The key is the English source text**, exactly as the web keys it:
//!   [`tr`]`("Settings")` is "设置" in zh and "Settings" in en, and a source
//!   the catalog lacks falls back to the English (`createUiText`,
//!   ui-text.tsx:17-37). [`tr_with`] interpolates `{name}` tokens the way the
//!   web does: a token with no matching param stays as written.
//! - **The catalog is the web's own** ([`zh`], generated by
//!   `tools/i18n/zh_catalog.py` from verbatim copies of `zh.ts`,
//!   `fleet-copy.ts`, `reasoning-copy.ts` and `session-config-copy.ts`),
//!   merged on the first Chinese lookup in the web loader's order — later
//!   tables win ([`catalog`]). An English session never builds it.
//! - **[`alias`]**: native copy that names the SAME control as a web string
//!   with different English (the board's "New chat" is the web's
//!   "New Session") renders that web key's translation. Every entry cites
//!   the web control; a test proves each target is a real web key.
//! - **The language** is the display preference (`screens::a9_prefs`, the
//!   web's `octoscode.web.display.v1`), published here by the launch path and
//!   the Settings control. [`generation`] changes on every switch, so the
//!   host re-renders every surface live ([`tree`] re-texts the static shell,
//!   the lowered surfaces re-lower because their DSL changed).
//! - Never applied to model, user or server prose: only call sites that
//!   carry product copy call [`tr`] (the web's rule, `zh.ts:1`).
